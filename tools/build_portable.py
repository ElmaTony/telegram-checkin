"""Build a native standalone directory on the current OS and archive it."""
import argparse
import hashlib
import json
import platform
import shutil
import subprocess
import sys
import tarfile
import re
from pathlib import Path
from zipfile import ZipFile, ZIP_DEFLATED

ROOT = Path(__file__).resolve().parents[1]
TARGETS = ('windows-x64', 'linux-x64', 'linux-arm64', 'macos-x64', 'macos-arm64')
DEPLOY_FILES = ('telegram-checkin.service', 'telegram-checkin-portable.service', 'telegram-checkin.env.example')


def copy_deployment_files(folder, root=ROOT):
    destination = folder/'deploy'
    destination.mkdir(exist_ok=True)
    for name in DEPLOY_FILES:
        shutil.copy2(root/'deploy'/name, destination/name)


def artifact_paths(root, version, target):
    if not re.fullmatch(r'\d+\.\d+\.\d+',version) or target not in TARGETS:raise ValueError('Invalid artifact identity')
    archive=Path(root)/('telegram-checkin-v'+version+'-'+target+('.zip' if target.startswith('windows') else '.tar.gz'))
    return archive,archive.with_name(archive.name+'.sha256')


def validate_artifact(path, version, target, commit):
    if path.suffix=='.zip':
        with ZipFile(path) as z:
            names=[n for n in z.namelist() if n.endswith('/NATIVE-MANIFEST.json')]
            if len(names)!=1:raise ValueError('Missing standalone manifest')
            manifest=json.loads(z.read(names[0]))
    else:
        with tarfile.open(path) as t:
            names=[m for m in t.getmembers() if m.name.endswith('/NATIVE-MANIFEST.json')]
            if len(names)!=1:raise ValueError('Missing standalone manifest')
            manifest=json.load(t.extractfile(names[0]))
    if any(manifest.get(key)!=value for key,value in {'version':version,'target':target,'commit':commit,'dirty':False}.items()):
        raise ValueError('Standalone package version, platform or source commit does not match')
    return manifest


def target_name():
    system = {'Windows':'windows', 'Linux':'linux', 'Darwin':'macos'}[platform.system()]
    arch = {'amd64':'x64', 'x86_64':'x64', 'aarch64':'arm64', 'arm64':'arm64'}[platform.machine().lower()]
    target = system+'-'+arch
    if target not in TARGETS:
        raise ValueError('此平台尚未加入发行矩阵')
    return target


def build(allow_dirty=False):
    version = (ROOT/'VERSION').read_text(encoding='utf-8').strip()
    dirty = bool(subprocess.check_output(['git','status','--porcelain'], cwd=ROOT))
    if dirty and not allow_dirty:
        raise RuntimeError('发行构建要求工作区干净；本地验证可使用 --allow-dirty，开发包不能发布')
    commit = subprocess.check_output(['git','rev-parse','HEAD'],cwd=ROOT,text=True).strip()
    target = target_name()
    work = ROOT/'build'/'native'
    work.mkdir(parents=True, exist_ok=True)
    (ROOT/'build'/'.telegram-checkin-build').write_text('Generated by tools/build_portable.py\n',encoding='utf-8')
    subprocess.run([sys.executable,'-m','PyInstaller','--noconfirm','--clean',
                    '--distpath',str(work/'dist'),'--workpath',str(work/'work'),str(ROOT/'telegram-checkin.spec')],cwd=ROOT,check=True)
    folder = work/'dist'/'telegram-checkin'
    for name in ('LICENSE','VERSION'):
        shutil.copy2(ROOT/name, folder/name)
    copy_deployment_files(folder)
    (folder/'START-HERE.txt').write_text(
        'Telegram 签到工作台 '+version+'\n\n'
        '首次运行：telegram-checkin --install-browser（Windows 使用 telegram-checkin.exe）\n'
        'Linux 如缺系统库：sudo ./telegram-checkin --install-browser-deps\n'
        '启动工作台：双击程序，或执行 ./telegram-checkin\n'
        '诊断环境：telegram-checkin --doctor --browser\n'
        '配置和登录资料保存在系统用户数据目录；用 --home 路径自定义。\n'
        '升级时只替换程序目录；不要删除原数据目录。\n\n'
        '使用说明：https://github.com/ElmaTony/telegram-checkin#readme\n',encoding='utf-8')
    files = {p.relative_to(folder).as_posix():hashlib.sha256(p.read_bytes()).hexdigest()
             for p in sorted(folder.rglob('*')) if p.is_file()}
    (folder/'NATIVE-MANIFEST.json').write_text(json.dumps(
        {'version':version,'target':target,'commit':commit,'dirty':dirty,'sha256':files},ensure_ascii=False,indent=2),encoding='utf-8')
    output = ROOT/'dist';output.mkdir(exist_ok=True)
    basename = 'telegram-checkin-v'+version+'-'+target
    if target.startswith('windows'):
        archive = output/(basename+'.zip')
        with ZipFile(archive,'w',compression=ZIP_DEFLATED) as z:
            for p in sorted(folder.rglob('*')):
                if p.is_file():z.write(p, basename+'/'+p.relative_to(folder).as_posix())
    else:
        archive = output/(basename+'.tar.gz')
        with tarfile.open(archive,'w:gz') as t:
            t.add(folder,arcname=basename)
    archive.with_name(archive.name+'.sha256').write_text(hashlib.sha256(archive.read_bytes()).hexdigest()+'  '+archive.name+'\n',encoding='ascii')
    return archive


if __name__ == '__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--allow-dirty',action='store_true')
    args=parser.parse_args()
    print(build(args.allow_dirty))
